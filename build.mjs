import { mkdir, readFile, writeFile } from 'node:fs/promises';
const here = new URL('./', import.meta.url);
const source = await Promise.all(['core.js', 'remote.js', 'preview-state.js', 'client-entry.js'].map(file => readFile(new URL(`src/${file}`, here), 'utf8')));
const body = source.map(text => text.replace(/^export /gm, '')).join('\n');
await mkdir(new URL('lib/', here), { recursive: true });
await writeFile(new URL('lib/client.js', here), `// Generated by build.mjs; edit the source modules.\nwindow.__ModuleLoader__.load({\n  id: '@catwithoutear/dsh-prompt-assist',\n  factory(require) {\n${body}\nreturn makeClient(require('react'));\n  },\n});\n`);
